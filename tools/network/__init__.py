"""
tools.network —— 细胞器互作网络的**重建**与涌现特征度量
=======================================================

背景（为什么需要这个包）
------------------------
项目原有的 ``code/analyze_emergent_entropy.m`` 只做了这样一件事：
对"每张图每个区域一行"的特征表逐列做直方图统计，然后把直方图熵叫作
"网络香农熵"、把幂律拟合的指数叫作"李亚普诺夫指数"。
**整条流水线里从来没有构建过任何网络**，因此那两个名字都是错误的标签。

本包补上真正缺失的一环：

``build.py``
    把分割出来的区域真正连成一张图（``OrganelleNetwork``），
    提供 5 种显式的邻接判据，全部可复现、可序列化。
``metrics.py``
    在**真正建好的图**上计算度分布熵、边权熵、聚类系数、路径长度、
    模块度、状态转移熵（马尔可夫链熵率）、相邻节点互信息、鲁棒性等指标，
    每个函数的文档字符串都写明它度量的是哪个概率分布、单位是什么。
``dynamics.py``
    正确的 Rosenstein 李亚普诺夫指数实现（AMI 估 τ、FNN 估 m、Theiler 窗、
    指定标度区拟合 + R² + ``reliable`` 标志）。数据不足时它**拒绝给出数字**。
``run_analysis.py``
    命令行驱动：逐图建网 → 算指标 → 汇总（每个汇总值都带 N）→
    输出 ``per_image.json`` / ``summary.json`` / ``metrics.csv`` / ``REPORT.md``。

重要免责声明
------------
本包重建的是**空间邻近性网络**（spatial proximity graph），
它只是"细胞器互作"的一个**代理量**，不是真实的互作测量。
详见 ``README.md`` 的"局限"一节。
"""

